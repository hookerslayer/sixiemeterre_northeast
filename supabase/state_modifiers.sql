-- State modifiers: administrator-issued effects and player proposals.
create table if not exists public.state_modifiers (
    id bigint generated by default as identity primary key,
    owner text not null,
    effect_key text not null,
    value numeric not null,
    scope_type text not null default 'state',
    scope_value text,
    target_type text,
    item_name text,
    source text not null,
    source_type text not null check (source_type in ('administrator', 'player_proposal')),
    status text not null check (status in ('pending', 'active', 'rejected', 'expired', 'revoked')),
    issued_turn integer not null,
    starts_turn integer not null,
    ends_turn integer,
    created_by uuid references auth.users(id) on delete set null,
    decided_by uuid references auth.users(id) on delete set null,
    decided_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint state_modifiers_value_range check (value between -1000000 and 1000000),
    constraint state_modifiers_scope_type check (scope_type in ('state','estate','culture','religion','resource','good','need','province','marker','army')),
    constraint state_modifiers_target_type check (target_type is null or target_type in ('province','marker','city','large_city','monastery','fortress','army','fleet')),
    constraint state_modifiers_turn_range check (starts_turn > 0 and (ends_turn is null or ends_turn >= starts_turn)),
    constraint state_modifiers_text_lengths check (
        length(owner) between 1 and 120 and length(effect_key) between 1 and 80
        and length(source) between 1 and 500 and (scope_value is null or length(scope_value) <= 160)
        and (item_name is null or length(item_name) <= 160)
    )
);

create index if not exists state_modifiers_owner_status_turn_idx
    on public.state_modifiers(owner, status, starts_turn, ends_turn);

alter table public.state_modifiers enable row level security;
revoke all on public.state_modifiers from anon, authenticated;
grant select on public.state_modifiers to authenticated;

drop policy if exists "State members and admins read modifiers" on public.state_modifiers;
create policy "State members and admins read modifiers"
    on public.state_modifiers for select to authenticated
    using (exists (
        select 1 from public.profiles p
        where p.id = (select auth.uid()) and (p.role = 'admin' or p.owner = state_modifiers.owner)
    ));

create or replace function public.submit_state_modifier_proposal(
    p_effect_key text,
    p_value numeric,
    p_scope_type text,
    p_scope_value text,
    p_target_type text,
    p_item_name text,
    p_source text,
    p_starts_turn integer,
    p_ends_turn integer default null
) returns public.state_modifiers
language plpgsql security definer set search_path = '' as $function$
declare caller public.profiles%rowtype; current_turn integer; modifier_row public.state_modifiers%rowtype;
begin
    select * into caller from public.profiles where id = (select auth.uid());
    if caller.id is null or caller.role <> 'player' or nullif(caller.owner, '') is null then
        raise exception 'Only a state player can propose a modifier' using errcode = '42501';
    end if;
    if p_effect_key not in ('estate_loyalty_pp','culture_loyalty_pp','religion_loyalty_pp','crime_rate_pp','corruption_rate_pp','tax_income_pct','internal_trade_income_pct','resource_production_pct','good_production_pct','guild_capacity_pct','consumption_pct','spoilage_pct','storage_capacity_pct','population_growth_pct','treasury_income_z','treasury_expense_z','prestige_income_op','prestige_expense_op','military_upkeep_pct','supply_consumption_pct','supply_capacity_pct','morale_change_pp','military_recruitment_cost_pct','colonization_cost_pct','spy_network_growth_pct','spy_operation_success_pp','spy_exposure_chance_pp','counterintelligence_success_pp','assimilation_duration_pct','battle_strength_pct','siege_work_gain_pct')
       or p_scope_type not in ('state','estate','culture','religion','resource','good','need','province','marker','army')
       or (p_effect_key in ('estate_loyalty_pp') and p_scope_type not in ('state','estate'))
       or (p_effect_key in ('culture_loyalty_pp') and p_scope_type not in ('state','culture'))
       or (p_effect_key in ('religion_loyalty_pp') and p_scope_type not in ('state','religion'))
       or (p_effect_key in ('resource_production_pct') and p_scope_type not in ('state','culture','religion','resource','province'))
       or (p_effect_key in ('good_production_pct') and p_scope_type not in ('state','culture','religion','good','marker'))
       or (p_effect_key in ('guild_capacity_pct') and p_scope_type not in ('state','culture','religion','marker'))
       or (p_effect_key in ('consumption_pct') and p_scope_type not in ('state','need','culture','religion','province','marker'))
       or (p_effect_key in ('spoilage_pct') and p_scope_type not in ('state','resource','good','marker'))
       or (p_effect_key in ('storage_capacity_pct') and p_scope_type not in ('state','marker'))
       or (p_effect_key in ('military_upkeep_pct','supply_consumption_pct','supply_capacity_pct','morale_change_pp') and p_scope_type not in ('state','army'))
       or (p_effect_key in ('assimilation_duration_pct') and p_scope_type not in ('state','province','marker'))
       or (p_effect_key in ('battle_strength_pct') and p_scope_type not in ('state','army'))
       or (p_effect_key in ('siege_work_gain_pct') and p_scope_type not in ('state','army'))
       or (p_effect_key not in ('estate_loyalty_pp','culture_loyalty_pp','religion_loyalty_pp','resource_production_pct','good_production_pct','guild_capacity_pct','consumption_pct','spoilage_pct','storage_capacity_pct','military_upkeep_pct','supply_consumption_pct','supply_capacity_pct','morale_change_pp','assimilation_duration_pct','battle_strength_pct','siege_work_gain_pct') and p_scope_type <> 'state')
       or p_value is null or p_value not between -1000000 and 1000000
       or nullif(trim(p_source), '') is null or length(p_source) > 500
       or p_starts_turn is null or p_starts_turn < 1
       or (p_ends_turn is not null and p_ends_turn < p_starts_turn)
       or (p_target_type is not null and p_target_type not in ('province','marker','city','large_city','monastery','fortress','army','fleet')) then
        raise exception 'Invalid modifier proposal';
    end if;
    select turn into current_turn from public.game_calendar where singleton = true;
    if p_starts_turn < current_turn then raise exception 'Modifier cannot start before the current turn'; end if;
    insert into public.state_modifiers(owner,effect_key,value,scope_type,scope_value,target_type,item_name,source,source_type,status,issued_turn,starts_turn,ends_turn,created_by)
    values(caller.owner,p_effect_key,p_value,p_scope_type,nullif(trim(p_scope_value),''),p_target_type,nullif(trim(p_item_name),''),trim(p_source),'player_proposal','pending',current_turn,p_starts_turn,p_ends_turn,caller.id)
    returning * into modifier_row;
    return modifier_row;
end;
$function$;

