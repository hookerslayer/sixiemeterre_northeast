create or replace function public.admin_decide_state_modifier(p_modifier_id bigint, p_decision text)
returns public.state_modifiers
language plpgsql security definer set search_path = '' as $function$
declare caller public.profiles%rowtype; modifier_row public.state_modifiers%rowtype; current_turn integer;
begin
    select * into caller from public.profiles where id = (select auth.uid());
    if caller.id is null or caller.role <> 'admin' then raise exception 'Only an administrator can decide modifier proposals' using errcode = '42501'; end if;
    if p_decision not in ('approve','reject','revoke') then raise exception 'Invalid modifier decision'; end if;
    select turn into current_turn from public.game_calendar where singleton = true;
    if p_decision = 'approve' and exists(select 1 from public.state_modifiers where id=p_modifier_id and ends_turn is not null and ends_turn < current_turn) then
        raise exception 'Proposal validity period has already ended';
    end if;
    update public.state_modifiers
       set status = case when p_decision = 'approve' then 'active' when p_decision = 'reject' then 'rejected' else 'revoked' end,
           starts_turn = case when p_decision = 'approve' then greatest(starts_turn,current_turn) else starts_turn end,
           decided_by = caller.id, decided_at = now(), updated_at = now()
     where id = p_modifier_id
       and ((p_decision in ('approve','reject') and status = 'pending') or (p_decision = 'revoke' and status = 'active'))
     returning * into modifier_row;
    if modifier_row.id is null then raise exception 'Modifier was not found or is no longer actionable'; end if;
    return modifier_row;
end;
$function$;

create or replace function public.expire_state_modifiers_after_turn()
returns trigger language plpgsql security definer set search_path = '' as $function$
begin
    if new.turn > old.turn then
        update public.state_modifiers set status = 'expired', updated_at = now()
         where status = 'active' and ends_turn is not null and ends_turn < new.turn;
    end if;
    return new;
end;
$function$;

drop trigger if exists expire_state_modifiers_after_turn on public.game_calendar;
create trigger expire_state_modifiers_after_turn after update of turn on public.game_calendar
for each row execute function public.expire_state_modifiers_after_turn();

